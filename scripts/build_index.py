#!/usr/bin/env python3
"""Regenerate references/index.yaml and patterns/index.yaml from the entries.

    python scripts/build_index.py          # write the index files
    python scripts/build_index.py --check  # exit 1 if they are out of date
"""
from __future__ import annotations

import argparse
import sys

import yaml

from library import ROOT, load_entries, load_patterns

HEADER = "# Generated by scripts/build_index.py – do not edit by hand.\n"


def render() -> dict[str, str]:
    refs = [
        {
            "id": e["id"],
            "title": e["title"],
            "url": e["url"],
            "path": e["_path"],
            "source_reports": e["source_reports"],
            "categories": e["categories"],
            "design_language": e["design_language"],
            "availability": e["availability"],
            "patterns": e["patterns"],
            "url_status": e["verification"]["status"],
        }
        for e in load_entries()
    ]
    pats = [
        {
            "id": p["id"],
            "name": p["name"],
            "group": p["group"],
            "path": p["_path"],
            "source_reports": p["source_reports"],
            "supporting_references": p["supporting_references"],
        }
        for p in load_patterns()
    ]
    dump = lambda d: HEADER + yaml.safe_dump(d, allow_unicode=True, sort_keys=False, width=110)  # noqa: E731
    groups: dict[str, list[dict]] = {}
    for p in load_patterns():
        groups.setdefault(p["group"], []).append(p)
    lines = [
        "<!-- Generated by scripts/build_index.py – do not edit by hand. -->",
        "# Pattern Library",
        "",
        f"{len(pats)} reusable patterns distilled from both research reports. Each pattern file has YAML front matter "
        "(id, provenance, supporting references, suitable/unsuitable project types) and sections for UX goal, "
        "visual characteristics, interaction behavior, implementation, accessibility and performance.",
        "",
        "Patterns are abstractions across several references – use them to compose original designs, "
        "never to copy a single site.",
        "",
    ]
    for group in sorted(groups):
        lines += [f"## {group}", "", "| ID | Pattern | Suitable for | Supporting references |", "|---|---|---|---|"]
        for p in groups[group]:
            name = f"[{p['name']}]({p['_path'].removeprefix('patterns/')})"
            lines.append(f"| `{p['id']}` | {name} | {', '.join(p['suitable_for'][:3])} | "
                         f"{', '.join(p['supporting_references'])} |")
        lines.append("")
    return {
        "patterns/README.md": "\n".join(lines),
        "references/index.yaml": dump({"count": len(refs), "references": refs}),
        "patterns/index.yaml": dump({"count": len(pats), "patterns": pats}),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check whether the index files are current")
    args = parser.parse_args()
    stale = []
    for rel_path, content in render().items():
        path = ROOT / rel_path
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(rel_path)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {rel_path}")
    if stale:
        sys.exit("out of date (run python scripts/build_index.py): " + ", ".join(stale))


if __name__ == "__main__":
    main()
