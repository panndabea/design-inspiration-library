#!/usr/bin/env python3
"""Build the processed research files from the untouched originals.

For every report registered in REPORTS this script writes:

* research/processed/<slug>.md -- the report text with tool citation markers
  (``citeturn...``) removed and a provenance header added.
* research/processed/<slug>-raw-references.yaml -- every reference the report
  mentions (table rows and inline links), with section, row cells and
  line number, so curated entries can be traced back to the source.

Re-run after adding or replacing a report:  python scripts/extract_references.py
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required: pip install -r requirements.txt")

ROOT = Path(__file__).resolve().parent.parent

REPORTS = {
    "interactive-learning": {
        "original": "research/original/interactive-learning/deep-research-report-18.md",
        "title": "Die schönsten visuellen und interaktiven Lernwebseiten im Internet",
        "topic": "Interactive Learning & Beautiful Web Experiences",
    },
    "beyond-dashboards": {
        "original": "research/original/beyond-dashboards/deep-research-report-19.md",
        "title": "Beyond Dashboards – Die Zukunft visueller Informationssysteme",
        "topic": "Beyond Dashboards",
    },
}

CITATION = re.compile(r"\s*\ue200cite(?:\ue202turn\w+?)+\ue201|\s*cite(?:turn\d+[a-z]+\d+)+")
LINK = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")


def strip_citations(text: str) -> str:
    return CITATION.sub("", text)


def split_row(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def plain(cell: str) -> str:
    return strip_citations(LINK.sub(r"\1", cell).replace("**", "")).strip()


def extract(slug: str, meta: dict) -> tuple[str, list[dict]]:
    src = (ROOT / meta["original"]).read_text(encoding="utf-8")
    clean = strip_citations(src)
    refs: list[dict] = []
    seen_rows: set[int] = set()
    section = subsection = ""
    header: list[str] | None = None
    for lineno, line in enumerate(clean.splitlines(), start=1):
        if line.startswith("## "):
            section, subsection, header = line[3:].strip(), "", None
            continue
        if line.startswith("### "):
            subsection, header = line[4:].strip(), None
            continue
        if line.startswith("|"):
            cells = split_row(line)
            if all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                continue
            if header is None:
                header = [plain(c) for c in cells]
                continue
            title_cell = next((c for c in cells if LINK.search(c)), None)
            # Unlinked rows are only references in the reference catalogue table;
            # elsewhere they are patterns, principles or concepts.
            if title_cell is None and section != "Curated Inspiration Library":
                continue
            first_text = next((c for c in cells if c and not c.isdigit()), "")
            link = LINK.search(title_cell) if title_cell else None
            title = link.group(1) if link else plain(first_text).split(" — ")[0]
            if not title:
                continue
            refs.append({
                "title": title,
                "url": link.group(2) if link else None,
                "section": " / ".join(s for s in (section, subsection) if s),
                "line": lineno,
                "kind": "table-row",
                "fields": {h or f"col{i}": plain(c) for i, (h, c) in enumerate(zip(header, cells))},
            })
            seen_rows.add(lineno)
            continue
        header = None
        for m in LINK.finditer(line):
            refs.append({
                "title": m.group(1),
                "url": m.group(2),
                "section": " / ".join(s for s in (section, subsection) if s),
                "line": lineno,
                "kind": "inline-link",
                "context": plain(line)[:400],
            })
    for i, ref in enumerate(refs, start=1):
        ref["raw_id"] = f"{slug}-{i:03d}"
    return clean, refs


def main() -> None:
    out_dir = ROOT / "research/processed"
    out_dir.mkdir(parents=True, exist_ok=True)
    for slug, meta in REPORTS.items():
        clean, refs = extract(slug, meta)
        sha = hashlib.sha256((ROOT / meta["original"]).read_bytes()).hexdigest()
        head = (
            f"<!-- Generated by scripts/extract_references.py from {meta['original']}\n"
            f"     sha256 {sha}. Only tool citation markers were removed; do not edit by hand. -->\n\n"
        )
        (out_dir / f"{slug}.md").write_text(head + clean, encoding="utf-8")
        doc = {
            "report": slug,
            "topic": meta["topic"],
            "title": meta["title"],
            "original": meta["original"],
            "original_sha256": sha,
            "language": "de",
            "reference_count": len(refs),
            "references": [{"raw_id": r.pop("raw_id"), **r} for r in refs],
        }
        with open(out_dir / f"{slug}-raw-references.yaml", "w", encoding="utf-8") as fh:
            yaml.safe_dump(doc, fh, allow_unicode=True, sort_keys=False, width=110)
        print(f"{slug}: {len(refs)} raw references, {len({r['url'] for r in refs if r['url']})} unique URLs")


if __name__ == "__main__":
    main()
